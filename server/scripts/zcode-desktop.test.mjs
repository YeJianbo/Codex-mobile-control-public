import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {DatabaseSync} from 'node:sqlite';
import {syncZcodeDesktopSession} from '../src/services/zcodeDesktop.ts';

test('desktop catalog keeps the original session, project and user presentation',t=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'zcode-desktop-'));
  const previous={base:process.env.ZCODE_DATA_BASE_DIR,storage:process.env.ZCODE_STORAGE_DIR};
  let native,index;
  process.env.ZCODE_DATA_BASE_DIR=root;delete process.env.ZCODE_STORAGE_DIR;
  t.after(()=>{index?.close();native?.close();for(const [key,value] of [['ZCODE_DATA_BASE_DIR',previous.base],['ZCODE_STORAGE_DIR',previous.storage]])if(value===undefined)delete process.env[key];else process.env[key]=value;fs.rmSync(root,{recursive:true,force:true});});
  const home=path.join(root,'.zcode');fs.mkdirSync(path.join(home,'cli','db'),{recursive:true});fs.mkdirSync(path.join(home,'v2'));
  native=new DatabaseSync(path.join(home,'cli','db','db.sqlite'));
  native.exec(`CREATE TABLE session(id TEXT PRIMARY KEY,directory TEXT,workspace_id TEXT,title TEXT,title_source TEXT,time_created INTEGER,time_updated INTEGER,time_deleted INTEGER);
    INSERT INTO session VALUES('sess_original','/work/project',NULL,'New chat','default',1,2,NULL);`);
  index=new DatabaseSync(path.join(home,'v2','tasks-index.sqlite'));
  index.exec(`CREATE TABLE hosts(host_id TEXT PRIMARY KEY,kind TEXT);INSERT INTO hosts VALUES('local','local');
    CREATE TABLE projects(project_id TEXT PRIMARY KEY,host_id TEXT,name TEXT,position INTEGER,created_at INTEGER,updated_at INTEGER,deleted INTEGER DEFAULT 0);
    CREATE TABLE project_roots(project_id TEXT,root_path TEXT,position INTEGER,is_primary INTEGER);
    CREATE TABLE tasks(workspace_key TEXT,workspace_path TEXT,task_id TEXT,title TEXT,task_status TEXT,provider TEXT,mode TEXT,model TEXT,created_at INTEGER,updated_at INTEGER,meta_json TEXT,host_id TEXT,root_path TEXT,project_id TEXT,cli_title TEXT,cli_title_source TEXT,cli_created_at INTEGER,cli_updated_at INTEGER,title_overridden INTEGER DEFAULT 0,deleted INTEGER DEFAULT 0,archived INTEGER DEFAULT 0,PRIMARY KEY(workspace_key,task_id));`);
  assert.equal(syncZcodeDesktopSession('sess_original',{title:'控制台原会话',model:'account/GLM-5.3',status:'running'}),true);
  let row=index.prepare('SELECT * FROM tasks').get();
  assert.equal(row.task_id,'sess_original');assert.equal(row.title,'控制台原会话');assert.equal(row.task_status,'running');
  assert.equal(index.prepare('SELECT root_path FROM project_roots').get().root_path,'/work/project');
  index.prepare("UPDATE tasks SET title='电脑改名',title_overridden=1,archived=1").run();
  assert.equal(syncZcodeDesktopSession('sess_original',{title:'后续提问',status:'completed'}),true);
  row=index.prepare('SELECT * FROM tasks').get();assert.equal(row.title,'电脑改名');assert.equal(row.archived,1);assert.equal(row.task_status,'completed');assert.equal(row.model,'account/GLM-5.3');
  assert.equal(index.prepare('SELECT count(*) n FROM projects').get().n,1);
  assert.equal(native.prepare('SELECT count(*) n FROM session').get().n,1);
  index.prepare('UPDATE tasks SET deleted=1').run();
  assert.equal(syncZcodeDesktopSession('sess_original',{status:'running'}),false);
  assert.equal(index.prepare('SELECT deleted FROM tasks').get().deleted,1);
  assert.equal(syncZcodeDesktopSession('sess_missing',{status:'running'}),false);
  process.env.ZCODE_STORAGE_DIR=path.join(root,'isolated');
  assert.equal(syncZcodeDesktopSession('sess_original',{status:'running'}),false);
});
