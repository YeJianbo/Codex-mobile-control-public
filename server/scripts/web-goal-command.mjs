import assert from 'node:assert/strict';
import path from 'node:path';

export async function auditGoalCommand(page,artifacts,{base,token}){
  const drawer=async()=>{
    if(!await page.locator('#sidebar').evaluate(node=>node.classList.contains('open')))
      await page.locator(await page.locator('#mobileDrawer').isVisible()?'#mobileDrawer':'#openDrawer').click();
  };
  await drawer();await page.locator('#harnessBtn').click();
  await page.locator('.harness-option').filter({hasText:'Codex'}).click();
  await drawer();await page.locator('#projects .project-row').filter({hasText:'Other Workspace'}).click();
  await page.locator('#prompt').fill('建立目标检查会话');await page.locator('#sendBtn').click();
  await page.waitForFunction(()=>document.querySelector('#events').textContent.includes('建立目标检查会话')&&document.querySelector('#sendBtn').getAttribute('aria-label')==='发送消息');
  const before=await page.locator('.message.user').count();
  const bodies=[];let fail=true;
  await page.route('**/api/threads/*/goal',async route=>{
    const body=route.request().postDataJSON();bodies.push(body);
    if(fail){fail=false;return route.fulfill({status:503,json:{error:'目标保存失败'}});}
    await route.fulfill({json:{goal:{goalId:'inline-goal',objective:body.objective,status:body.status}}});
  });
  const objective='基于本地科研工作流优化项目和使用体验';
  await page.locator('#prompt').fill('/goal '+objective);await page.locator('#sendBtn').click();
  await page.getByText('目标保存失败',{exact:true}).waitFor();
  assert.equal(await page.locator('#prompt').inputValue(),'/goal '+objective);
  await page.locator('#sendBtn').click();
  await page.waitForFunction(objective=>document.querySelector('#goalChipText').textContent==='目标：'+objective,objective);
  assert.deepEqual(bodies,[{objective,status:'active'},{objective,status:'active'}]);
  assert.equal(await page.locator('#prompt').inputValue(),'');
  assert.equal(await page.locator('.message.user').count(),before,'目标命令不能作为普通消息发送');
  await page.screenshot({path:path.join(artifacts,'web-goal-command-198.png')});
  await page.unroute('**/api/threads/*/goal');
  console.log('PASS /goal 内容直接保存并显示目标，失败保留原输入');
  await drawer();await page.locator('#newThreadBtn').click();
  await page.locator('#fileInput').setInputFiles({name:'goal-notes.txt',mimeType:'text/plain',buffer:Buffer.from('unsent goal notes')});
  await page.locator('#fileDrafts .file-attachment').waitFor();
  const fresh='从新会话建立目标';
  await page.locator('#prompt').fill('/goal '+fresh);await page.locator('#sendBtn').click();
  await page.waitForFunction(text=>document.querySelector('#goalChipText').textContent==='目标：'+text,fresh);
  assert.equal(await page.locator('.message.user').count(),0,'新目标不能产生普通用户消息');
  await page.locator('#fileDrafts .file-attachment').filter({hasText:'goal-notes.txt'}).waitFor();
  const threads=await (await page.request.get(base+'/api/threads',{headers:{Authorization:'Bearer '+token}})).json();
  const thread=threads.threads.find(row=>row.goal?.objective===fresh);
  assert(thread);assert.equal(thread.title,fresh);assert.equal(thread.goal.status,'active');
  const files=await page.evaluate(()=>JSON.parse(localStorage.getItem('cmc.fileDrafts')||'{}'));
  assert(files['thread:'+thread.id].some(file=>file.name==='goal-notes.txt'),'待发文件跟随新会话且没有被当作已发送附件消耗');
  await page.screenshot({path:path.join(artifacts,'web-fresh-goal-199.png')});
  console.log('PASS 新会话直接创建目标并保留待发文件');
  let drop=false,accepted,hold=false,releaseEvents,missingNotice='',lastAccepted;const commands=[],held=[];
  const confirmation=new Promise(resolve=>{accepted=resolve;});
  await page.routeWebSocket('**/ws?*',socket=>{
    const server=socket.connectToServer();
    releaseEvents=()=>{hold=false;for(const message of held.splice(0))socket.send(message);};
    socket.onMessage(message=>{commands.push(JSON.parse(String(message)));server.send(message);});
    server.onMessage(message=>{
      const event=JSON.parse(String(message));
      if(event.type==='command.accepted')lastAccepted=event;
      if(missingNotice==='receipt-only'&&['thread.started','user.message','command.accepted'].includes(event.type))return;
      if(missingNotice&&(event.type==='thread.started'||missingNotice==='accepted-only'&&event.type==='user.message'))return;
      if(hold){held.push(message);return;}
      if(drop&&['thread.started','command.accepted'].includes(event.type)){
        if(event.type==='command.accepted')accepted(event);
        return;
      }
      socket.send(message);
    });
  });
  await page.reload();
  await page.waitForFunction(()=>!document.querySelector('#newThreadBtn').disabled);
  await drawer();await page.locator('#newThreadBtn').click();
  await page.locator('#fileInput').setInputFiles({name:'recovered-goal.txt',mimeType:'text/plain',buffer:Buffer.from('keep after reload')});
  await page.locator('#fileDrafts .file-attachment').filter({hasText:'recovered-goal.txt'}).waitFor();
  drop=true;
  await page.locator('#prompt').fill('/goal 刷新后恢复目标和附件');await page.locator('#sendBtn').click();
  const event=await confirmation;
  drop=false;await page.reload();
  await page.waitForFunction(()=>document.querySelector('#goalChipText').textContent==='目标：刷新后恢复目标和附件');
  const recovered=await page.evaluate(()=>JSON.parse(localStorage.getItem('cmc.fileDrafts')||'{}'));
  assert(recovered['thread:'+event.threadId]?.some(file=>file.name==='recovered-goal.txt'),'丢失实时通知后，回执恢复必须把待发文件归到新会话');
  await page.locator('#fileDrafts .file-attachment').filter({hasText:'recovered-goal.txt'}).waitFor();
  assert.equal(await page.locator('#prompt').inputValue(),'');
  assert.equal(await page.locator('.message.user').count(),0);
  console.log('PASS 创建目标时丢失实时通知，刷新后从回执恢复目标及待发文件');
  await drawer();await page.locator('#newThreadBtn').click();
  await page.locator('#fileInput').setInputFiles({name:'retry-goal.txt',mimeType:'text/plain',buffer:Buffer.from('keep through retry')});
  await page.locator('#fileDrafts .file-attachment').filter({hasText:'retry-goal.txt'}).waitFor();
  const retryText='/goal 失败后重试目标设置';
  await page.locator('#prompt').fill(retryText);await page.locator('#sendBtn').click();
  await page.waitForFunction(text=>document.querySelector('#prompt').value===text,retryText);
  const submitted=commands.find(command=>command.initialText===retryText);assert(submitted);
  const receipt=await (await page.request.get(base+'/api/local-tasks/'+submitted.requestId,{headers:{Authorization:'Bearer '+token}})).json();
  assert.equal(receipt.request.state,'failed');
  await page.reload();
  await page.waitForFunction(text=>document.querySelector('#prompt').value===text,retryText);
  const patches=[];page.on('request',request=>{if(request.method()==='PATCH'&&/\/goal$/.test(request.url()))patches.push(request.url());});
  await page.locator('#sendBtn').click();
  await page.waitForFunction(()=>document.querySelector('#prompt').value==='');
  await page.waitForFunction(()=>!localStorage.getItem('cmc.pendingSubmit'));
  assert.equal(commands.filter(command=>command.requestId===submitted.requestId).length,2,'刷新后重试必须沿用原请求及模型设置');
  assert.equal(patches.length,0,'失败的创建目标不能改成只设置 active 的 PATCH');
  await page.locator('#fileDrafts .file-attachment').filter({hasText:'retry-goal.txt'}).waitFor();
  const retried=await (await page.request.get(base+'/api/threads',{headers:{Authorization:'Bearer '+token}})).json();
  const goals=retried.threads.filter(thread=>thread.goal?.objective==='失败后重试目标设置');
  assert.equal(goals.length,1);assert.equal(goals[0].id,receipt.request.threadId);assert.equal(goals[0].goal.status,'active');
  console.log('PASS 目标设置失败后刷新重试，复用原会话、请求与模型设置并保留附件');
  await drawer();await page.locator('#newThreadBtn').click();
  hold=true;
  const followup='创建期间继续输入';
  await page.locator('#prompt').fill(followup);await page.locator('#sendBtn').click();
  await page.locator('#prompt').fill(followup);
  await page.locator('#fileInput').setInputFiles({name:'next-message.txt',mimeType:'text/plain',buffer:Buffer.from('next message')});
  await page.locator('#fileDrafts .file-attachment').filter({hasText:'next-message.txt'}).waitFor();
  let finishUpload,uploadSeen;
  const seen=new Promise(resolve=>{uploadSeen=resolve;});
  const delayed=new Promise(resolve=>{finishUpload=resolve;});
  await page.route('**/api/uploads/files',async route=>{uploadSeen();await delayed;await route.continue();});
  await page.locator('#fileInput').setInputFiles({name:'late-message.txt',mimeType:'text/plain',buffer:Buffer.from('late message')});
  await seen;
  await page.waitForFunction(()=>document.querySelector('#prompt').value==='创建期间继续输入');
  const until=Date.now()+10000;
  while(!held.some(message=>JSON.parse(String(message)).type==='thread.started')&&Date.now()<until)await new Promise(resolve=>setTimeout(resolve,25));
  const created=held.map(message=>JSON.parse(String(message))).find(event=>event.type==='thread.started');assert(created);
  releaseEvents();
  await page.waitForFunction(id=>JSON.parse(localStorage.getItem('cmc.drafts')||'{}')['thread:'+id]==='创建期间继续输入',created.threadId);
  finishUpload();
  await page.locator('#fileDrafts .file-attachment').filter({hasText:'late-message.txt'}).waitFor();
  await page.unroute('**/api/uploads/files');
  assert.equal(await page.locator('#prompt').inputValue(),followup,'首条消息确认不得清除相同文字的新草稿');
  const migrated=await page.evaluate(()=>({text:JSON.parse(localStorage.getItem('cmc.drafts')||'{}'),files:JSON.parse(localStorage.getItem('cmc.fileDrafts')||'{}')}));
  assert.deepEqual(migrated.files['thread:'+created.threadId].map(file=>file.name).sort(),['late-message.txt','next-message.txt']);
  assert(!Object.entries(migrated.text).some(([key,value])=>key.includes('project:')&&value===followup));
  assert(!Object.entries(migrated.files).some(([key,files])=>key.includes('project:')&&files.some(file=>['late-message.txt','next-message.txt'].includes(file.name))));
  await page.reload();
  await page.waitForFunction(()=>!document.querySelector('#newThreadBtn').disabled);
  await drawer();await page.locator('#threads .thread-row').filter({hasText:followup}).first().click();
  await page.locator('#fileDrafts .file-attachment').filter({hasText:'late-message.txt'}).waitFor();
  assert.equal(await page.locator('#prompt').inputValue(),followup);
  console.log('PASS 新会话创建期间的相同文字新草稿、待发文件与延迟上传归入会话，刷新保留');

  await drawer();await page.locator('#newThreadBtn').click();
  await page.locator('#fileInput').setInputFiles({name:'first-message.txt',mimeType:'text/plain',buffer:Buffer.from('keep original attachment')});
  await page.locator('#fileDrafts .file-attachment').filter({hasText:'first-message.txt'}).waitFor();
  const failedText='失败后重试首条附件消息';
  await page.locator('#prompt').fill(failedText);await page.locator('#sendBtn').click();
  await page.waitForFunction(text=>document.querySelector('#prompt').value===text,failedText);
  await page.locator('#fileDrafts .file-attachment').filter({hasText:'first-message.txt'}).waitFor();
  await page.reload();
  await page.waitForFunction(()=>!document.querySelector('#newThreadBtn').disabled);
  await drawer();await page.locator('#threads .thread-row').filter({hasText:failedText}).first().click();
  await page.waitForFunction(text=>document.querySelector('#prompt').value===text,failedText);
  await page.locator('#fileDrafts .file-attachment').filter({hasText:'first-message.txt'}).waitFor();
  const pendingBefore=await page.evaluate(()=>JSON.parse(localStorage.getItem('cmc.pendingSubmit')||'null'));
  assert(pendingBefore);
  const countBefore=commands.length;
  await page.locator('#sendBtn').click();
  await page.getByText('上次提交结果待确认，请先查看会话；系统不会自动重发。',{exact:true}).waitFor();
  assert.equal(commands.length,countBefore,'待确认回执不能自动重发');
  // Explicitly confirmed failure permits a fresh submission; the default mock RPC error is uncertain.
  const receiptRoute='**/api/local-tasks/'+pendingBefore.requestId;
  await page.route(receiptRoute,async route=>{
    const response=await route.fetch(),body=await response.json();
    body.request.state='failed';body.request.error='首条消息已确认未提交';
    await route.fulfill({response,json:body});
  });
  await page.locator('#sendBtn').click();
  await page.waitForFunction(()=>document.querySelector('#events').textContent.includes('失败后重试首条附件消息')&&document.querySelector('#fileDrafts').hidden);
  await page.unroute(receiptRoute);
  const initial=commands.find(command=>command.initialText===failedText);
  const retriedMessage=commands.find(command=>command.type==='turn.start'&&command.text===failedText);
  assert(initial);assert(retriedMessage);assert.deepEqual(retriedMessage.files,initial.files);
  const remaining=await page.evaluate(()=>JSON.parse(localStorage.getItem('cmc.fileDrafts')||'{}'));
  assert(!Object.values(remaining).flat().some(file=>file.id===initial.files[0].id),'成功确认后移除已经提交的原附件');
  console.log('PASS 新会话首条消息失败后恢复原附件，刷新保留，重试完整提交并清理待发附件');

  for(const kind of ['message','accepted-only']){
    await drawer();await page.locator('#newThreadBtn').click();
    missingNotice=kind;hold=true;
    const text=kind==='message'?'仅消息确认建立会话':'仅发送回执建立会话';
    await page.locator('#prompt').fill(text);await page.locator('#sendBtn').click();
    await page.locator('#prompt').fill(text+' 后续草稿');
    await page.locator('#fileInput').setInputFiles({name:kind+'.txt',mimeType:'text/plain',buffer:Buffer.from('followup attachment')});
    await page.locator('#fileDrafts .file-attachment').filter({hasText:kind+'.txt'}).waitFor();
    const deadline=Date.now()+10000;
    while(!held.some(message=>JSON.parse(String(message)).type==='command.accepted')&&Date.now()<deadline)await new Promise(resolve=>setTimeout(resolve,25));
    const acceptedEvent=held.map(message=>JSON.parse(String(message))).find(event=>event.type==='command.accepted');assert(acceptedEvent);
    releaseEvents();
    await page.waitForFunction(({id,text})=>JSON.parse(localStorage.getItem('cmc.drafts')||'{}')['thread:'+id]===text,{id:acceptedEvent.threadId,text:text+' 后续草稿'});
    await page.locator('#threads .thread-row.active').filter({hasText:text}).waitFor({state:'attached'});
    assert.equal(await page.locator('#prompt').inputValue(),text+' 后续草稿');
    const files=await page.evaluate(()=>JSON.parse(localStorage.getItem('cmc.fileDrafts')||'{}'));
    assert(files['thread:'+acceptedEvent.threadId]?.some(file=>file.name===kind+'.txt'));
    missingNotice='';
    await drawer();await page.locator('#newThreadBtn').click();
    await drawer();await page.locator('#threads .thread-row').filter({hasText:text}).first().click();
    assert.equal(await page.locator('#prompt').inputValue(),text+' 后续草稿');
    await page.locator('#fileDrafts .file-attachment').filter({hasText:kind+'.txt'}).waitFor();
  }
  console.log('PASS 丢失创建通知时，由用户消息或单独成功回执关联新会话并保留后续草稿与附件');

  await drawer();await page.locator('#newThreadBtn').click();
  await page.locator('#fileInput').setInputFiles({name:'receipt-sent.txt',mimeType:'text/plain',buffer:Buffer.from('submitted file')});
  await page.locator('#fileDrafts .file-attachment').filter({hasText:'receipt-sent.txt'}).waitFor();
  missingNotice='receipt-only';lastAccepted=null;
  const repeated='回执恢复后保留相同的新草稿';
  await page.locator('#prompt').fill(repeated);await page.locator('#sendBtn').click();
  await page.locator('#prompt').fill(repeated);
  await page.locator('#fileInput').setInputFiles({name:'receipt-next.txt',mimeType:'text/plain',buffer:Buffer.from('next file')});
  await page.locator('#fileDrafts .file-attachment').filter({hasText:'receipt-next.txt'}).waitFor();
  const receiptDeadline=Date.now()+10000;
  while(!lastAccepted&&Date.now()<receiptDeadline)await new Promise(resolve=>setTimeout(resolve,25));
  assert(lastAccepted);
  const receiptThread=lastAccepted.threadId;
  missingNotice='';await page.reload();
  await page.waitForFunction(({id,text})=>!localStorage.getItem('cmc.pendingSubmit')&&JSON.parse(localStorage.getItem('cmc.drafts')||'{}')['thread:'+id]===text,{id:receiptThread,text:repeated});
  assert.equal(await page.locator('#prompt').inputValue(),repeated);
  await page.locator('#fileDrafts .file-attachment').filter({hasText:'receipt-next.txt'}).waitFor();
  assert.equal(await page.locator('#fileDrafts .file-attachment').filter({hasText:'receipt-sent.txt'}).count(),0);
  const receiptDrafts=await page.evaluate(()=>({text:JSON.parse(localStorage.getItem('cmc.drafts')||'{}'),files:JSON.parse(localStorage.getItem('cmc.fileDrafts')||'{}')}));
  assert(!Object.entries(receiptDrafts.text).some(([key,text])=>key.includes('project:')&&text===repeated));
  assert.deepEqual(receiptDrafts.files['thread:'+receiptThread].map(file=>file.name),['receipt-next.txt']);
  await drawer();await page.locator('#newThreadBtn').click();
  await drawer();await page.locator('#threads .thread-row').filter({hasText:repeated}).first().click();
  assert.equal(await page.locator('#prompt').inputValue(),repeated);
  console.log('PASS 全部实时确认丢失后，刷新由回执恢复相同文字新草稿和后续附件，只清理已提交文件');

  await page.waitForFunction(()=>document.querySelector('#sendBtn').getAttribute('aria-label')==='发送消息');
  hold=true;lastAccepted=null;
  await page.locator('#sendBtn').click();
  await page.waitForFunction(()=>document.querySelector('#prompt').value==='');
  await page.locator('#composerTools').click();
  await page.getByText('再次使用上一条',{exact:true}).click();
  assert.equal(await page.locator('#prompt').inputValue(),repeated);
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('cmc.pendingSubmit')||'{}').draftEdited),true);
  const reuseDeadline=Date.now()+10000;
  while(!lastAccepted&&Date.now()<reuseDeadline)await new Promise(resolve=>setTimeout(resolve,25));
  assert(lastAccepted);releaseEvents();
  await page.waitForFunction(()=>!localStorage.getItem('cmc.pendingSubmit'));
  assert.equal(await page.locator('#prompt').inputValue(),repeated);
  await page.reload();
  await page.waitForFunction(()=>!document.querySelector('#newThreadBtn').disabled);
  await drawer();await page.locator('#threads .thread-row').filter({hasText:repeated}).first().click();
  assert.equal(await page.locator('#prompt').inputValue(),repeated);
  console.log('PASS 再次使用历史消息作为新草稿，旧消息确认及刷新不会清除相同文字');

  const unsent='尚未发送的独立草稿';
  await page.locator('#prompt').fill(unsent);
  await page.locator('#fileInput').setInputFiles({name:'keep-draft.txt',mimeType:'text/plain',buffer:Buffer.from('preserve existing draft')});
  await page.locator('#fileDrafts .file-attachment').filter({hasText:'keep-draft.txt'}).waitFor();
  const beforeReuse=commands.length;
  await page.locator('#composerTools').click();await page.getByText('再次使用上一条',{exact:true}).click();
  assert.equal(await page.locator('#prompt').inputValue(),repeated+'\n\n'+unsent);
  await page.locator('#fileDrafts .file-attachment').filter({hasText:'keep-draft.txt'}).waitFor();
  await page.locator('#composerTools').click();await page.getByText('再次使用上一条',{exact:true}).click();
  assert.equal(await page.locator('#prompt').inputValue(),repeated+'\n\n'+unsent,'重复使用同一条历史消息不重复追加正文');
  const combined=await page.evaluate(()=>JSON.parse(localStorage.getItem('cmc.fileDrafts')||'{}'));
  const names=combined['thread:'+receiptThread].map(file=>file.name);
  assert(names.includes('receipt-next.txt'));assert(names.includes('keep-draft.txt'));
  assert.equal(new Set(names).size,names.length);
  assert.equal(commands.length,beforeReuse,'使用历史消息只编辑草稿，不发送');
  await page.reload();await page.waitForFunction(()=>!document.querySelector('#newThreadBtn').disabled);
  await drawer();await page.locator('#threads .thread-row').filter({hasText:repeated}).first().click();
  assert.equal(await page.locator('#prompt').inputValue(),repeated+'\n\n'+unsent);
  await page.locator('#fileDrafts .file-attachment').filter({hasText:'keep-draft.txt'}).waitFor();
  console.log('PASS 使用历史消息合并现有文字和文件、去重附件，不自动发送，刷新保留');

}
