import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

const home=await fs.mkdtemp(path.join(os.tmpdir(),'cmc-read-state-'));
process.env.CODEX_HOME=home;
process.env.CODEX_MOBILE_CONTROL_HOME=path.join(home,'gateway');
const {StateStore}=await import('../dist/services/stateStore.js');
const {desktopUnreadThreads,withThreadReadState}=await import('../dist/services/threadReadState.js');
const {readCodexThreadCompletion}=await import('../dist/services/codexSessions.js');
const store=new StateStore();await store.load();
const globalFile=path.join(home,'.codex-global-state.json');
const v1=(ids)=>({'electron-thread-read-state-v1':{version:1,unreadByIdentity:{account:{'local:host':ids,'durable:cloud':['cloud']}}},'unread-thread-ids-by-host-v1':{local:['stale']}});
assert.deepEqual(desktopUnreadThreads(v1(['t'])),new Set(['t']));
assert.deepEqual(desktopUnreadThreads(v1([])),new Set());
assert.deepEqual(desktopUnreadThreads({'electron-thread-read-state-v1':{version:1,unreadByIdentity:{a:{'local:host':['old']},b:{'local:other':['other']}}}}),new Set());
const dir=path.join(home,'sessions');await fs.mkdir(dir);
const file=path.join(dir,'rollout-t.jsonl');
const row=(at,type)=>JSON.stringify({timestamp:new Date(at).toISOString(),type:'event_msg',payload:{type}})+'\n';
await fs.writeFile(file,row(1000,'task_started')+row(2000,'task_complete'));
await fs.writeFile(globalFile,JSON.stringify(v1(['t'])));
const thread={id:'t',title:'title',status:'idle',updatedAt:new Date(9000).toISOString(),createdAt:new Date(1000).toISOString()};
let [result]=await withThreadReadState([thread],store);
assert.equal(result.unread,true);assert.equal(result.completedAt,2000);
store.markThreadRead('t',2000);
assert.equal((await withThreadReadState([thread],store))[0].unread,false);
await fs.appendFile(file,row(3000,'task_started'));
assert.equal(await readCodexThreadCompletion('t'),0);
assert.equal((await withThreadReadState([thread],store))[0].unread,false);
await fs.appendFile(file,row(4000,'task_completed'));
store.markThreadRead('t',1000);
assert.equal(store.threadReadThrough('t'),2000);
assert.equal((await withThreadReadState([thread],store))[0].unread,true);
await fs.writeFile(globalFile,JSON.stringify(v1([])));
assert.equal((await withThreadReadState([thread],store))[0].unread,false);
const reloaded=new StateStore();await reloaded.load();assert.equal(reloaded.threadReadThrough('t'),2000);
console.log('PASS: desktop read removal, account/host isolation, per-completion receipts, running suppression, and persisted receipts');
console.log('Fixture directory: '+home);
